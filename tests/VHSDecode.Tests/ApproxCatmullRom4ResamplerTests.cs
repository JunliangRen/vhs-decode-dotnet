    [Fact(DisplayName = "Approx Catmull-Rom4 f32 source matches exact widening for every output shape")]
    public void Float32SourceMatchesExactWideningForEveryOutputShape()
    {
        float[] floatSource = Enumerable.Range(0, 257)
            .Select(index => (float)((1_000_000.0 * Math.Sin(index * 0.071)) + (17.0 * index)))
            .ToArray();
        double[] widenedSource = Array.ConvertAll(floatSource, static value => (double)value);
        double[] positions = Enumerable.Range(0, 1_024)
            .Select(index => 0.5 + ((floatSource.Length - 2.0) * index / 1_023.0))
            .ToArray();
        positions[0] = double.NaN;
        positions[1] = double.NegativeInfinity;
        positions[^1] = double.PositiveInfinity;
        double[] levels = Enumerable.Range(0, positions.Length)
            .Select(index => 0.75 + (0.5 * ((index % 29) / 28.0)))
            .ToArray();
        const double SourcePositionShift = -0.3125;

        var expectedFloat = new float[positions.Length];
        var actualFloat = new float[positions.Length];
        ApproxCatmullRom4Resampler.Resample(
            widenedSource,
            positions,
            levels,
            SourcePositionShift,
            expectedFloat);
        ApproxCatmullRom4Resampler.Resample(
            floatSource,
            positions,
            levels,
            SourcePositionShift,
            actualFloat);
        Assert.True(
            MemoryMarshal.AsBytes(expectedFloat.AsSpan()).SequenceEqual(
                MemoryMarshal.AsBytes(actualFloat.AsSpan())),
            "Direct f32-source output differed from the same samples exactly widened to double.");

        var expectedDouble = new double[positions.Length];
        var actualDouble = new double[positions.Length];
        ApproxCatmullRom4Resampler.Resample(
            widenedSource,
            positions,
            levels,
            SourcePositionShift,
            expectedDouble);
        ApproxCatmullRom4Resampler.Resample(
            floatSource,
            positions,
            levels,
            SourcePositionShift,
            actualDouble);
        Assert.Equal(expectedDouble, actualDouble);

        var converter = new VideoOutputConverter(
            ire0: 4_000_000.25,
            hzIre: 100_000.125,
            outputZero: 256,
            vsyncIre: -40.0,
            outputScale: 512.25);
        var expectedUInt16 = new ushort[positions.Length];
        var actualUInt16 = new ushort[positions.Length];
        ApproxCatmullRom4Resampler.ResampleToUInt16(
            widenedSource,
            positions,
            levels,
            SourcePositionShift,
            converter,
            expectedUInt16);
        ApproxCatmullRom4Resampler.ResampleToUInt16(
            floatSource,
            positions,
            levels,
            SourcePositionShift,
            converter,
            actualUInt16);
        Assert.Equal(expectedUInt16, actualUInt16);

        foreach (double position in positions)
        {
            Assert.Equal(
                BitConverter.SingleToUInt32Bits(
                    ApproxCatmullRom4Resampler.Sample(widenedSource, position)),
                BitConverter.SingleToUInt32Bits(
                    ApproxCatmullRom4Resampler.Sample(floatSource, position)));
        }
    }

    [Fact(DisplayName = "Approx Catmull-Rom4 f32 source output is bit-deterministic")]
    public void Float32SourceOutputIsBitDeterministic()
    {
        float[] source = Enumerable.Range(0, 257)
            .Select(index => (float)((1_000_000.0 * Math.Sin(index * 0.071)) + (17.0 * index)))
            .ToArray();
        double[] positions = Enumerable.Range(0, 1_024)
            .Select(index => 1.0 + ((source.Length - 4.0) * index / 1_023.0))
            .ToArray();
        double[] levels = Enumerable.Range(0, positions.Length)
            .Select(index => 0.75 + (0.5 * ((index % 29) / 28.0)))
            .ToArray();
        var expected = new float[positions.Length];
        var actual = new float[positions.Length];
        ApproxCatmullRom4Resampler.Resample(source, positions, levels, 0.1875, expected);

