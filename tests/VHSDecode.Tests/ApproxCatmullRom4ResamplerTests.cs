    [Fact(DisplayName = "Approx Catmull-Rom4 AVX2/FMA output is bit-identical across shapes and tails")]
    public void ForcedVectorMatchesScalarAcrossOutputShapesAndTails()
    {
        if (!ApproxCatmullRom4Resampler.IsVectorizationSupported)
        {
            return;
        }

        double[] doubleSource = Enumerable.Range(0, 521)
            .Select(index =>
                (4_000_000.0 * Math.Sin((index * 0.071) + 0.13)) +
                (123_456.0 * Math.Cos(index * 0.017)) +
                (index * 0.03125))
            .ToArray();
        float[] floatSource = Array.ConvertAll(doubleSource, static value => (float)value);
        int[] outputLengths = [8, 9, 15, 16, 17, 31, 257];
        double[] shifts = [-100.25, -0.3125, 0.0, 0.1875, 123.75];
        var random = new Random(0x4CA7_4D11);

        foreach (int outputLength in outputLengths)
        {
            foreach (double shift in shifts)
            {
                var positions = new double[outputLength];
                var levels = new double[outputLength];
                for (int index = 0; index < outputLength; index++)
                {
                    positions[index] = -16.0 + (random.NextDouble() * (doubleSource.Length + 32.0));
                    levels[index] = -2.0 + (random.NextDouble() * 4.0);
                }

                positions[0] = double.NaN;
                positions[1] = double.NegativeInfinity;
                positions[2] = double.PositiveInfinity;
                positions[3] = 1.0 - shift;
                positions[4] = (doubleSource.Length - 3.0) - shift;
                positions[5] = 0.999_999_999 - shift;
                positions[6] = (doubleSource.Length - 2.999_999_999) - shift;
                levels[0] = -0.0;
                levels[1] = double.Epsilon;
                levels[2] = -double.Epsilon;

                AssertForcedModesMatch(
                    doubleSource,
                    floatSource,
                    positions,
                    levels,
                    shift,
                    $"length={outputLength}, shift={shift:R}");
            }
        }
    }

