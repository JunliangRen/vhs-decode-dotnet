    private static void AssertBitwiseEqual<T>(T[] expected, T[] actual, string scenario)
        where T : unmanaged
    {
        Assert.True(
            MemoryMarshal.AsBytes(expected.AsSpan()).SequenceEqual(MemoryMarshal.AsBytes(actual.AsSpan())),
            $"Bitwise mismatch for {scenario}.");
    }

    [Fact(DisplayName = "Approx Catmull-Rom4 rejects invalid buffer shapes")]
    public void RejectsInvalidBufferShapes()
    {
        Assert.Throws<ArgumentException>(() =>
            ApproxCatmullRom4Resampler.Sample([1.0, 2.0, 3.0], 1.0));
        Assert.Throws<ArgumentException>(() =>
            ApproxCatmullRom4Resampler.Sample(new float[] { 1.0f, 2.0f, 3.0f }, 1.0));

        double[] source = [1.0, 2.0, 3.0, 4.0];
        Assert.Throws<ArgumentException>(() =>
            ApproxCatmullRom4Resampler.Resample(source, [1.0], [], new float[1]));
        Assert.Throws<ArgumentException>(() =>
            ApproxCatmullRom4Resampler.Resample(source, [1.0], [1.0], new float[2]));
        Assert.Throws<ArgumentNullException>(() =>
            ApproxCatmullRom4Resampler.ResampleToUInt16(source, [1.0], [1.0], null!, new ushort[1]));

        float[] floatSource = [1.0f, 2.0f, 3.0f, 4.0f];
        Assert.Throws<ArgumentException>(() =>
            ApproxCatmullRom4Resampler.Resample(floatSource, [1.0], [], new float[1]));
        Assert.Throws<ArgumentException>(() =>
            ApproxCatmullRom4Resampler.Resample(floatSource, [1.0], [1.0], new float[2]));
        Assert.Throws<ArgumentNullException>(() =>
            ApproxCatmullRom4Resampler.ResampleToUInt16(
                floatSource,
                [1.0],
                [1.0],
                null!,
                new ushort[1]));
    }
